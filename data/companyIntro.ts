function hashIndex(slug: string, length: number): number {
  let hash = 0
  for (let i = 0; i < slug.length; i++) {
    hash = (hash * 31 + slug.charCodeAt(i)) % length
  }
  return Math.abs(hash) % length
}

export function generateIntro(c: CompanyForIntro): string {
  if (c.slug === 'saizen-666') return introSaizen()
  const primaryNumber = c.numbers?.[0] ?? 2
  const templates = primaryNumber === 1 ? templates1 : primaryNumber === 3 ? templates3 : primaryNumber === 4 ? templates4 : templates2
  const index = hashIndex(c.slug, templates.length)
  return templates[index](c)
}
